// Генератор инструкции для копайтера стихов: собирается из текущей формы
// (жанр, голос, язык) + правил жанра. Пользователь может править перед отправкой.

// правила стиха по жанровым ключам: список [ключевые слова, правило]
const GENRE_RULES = [
  [['панк', 'пост-панк', 'гранж', 'нойз'], 'Рваные короткие строки, лозунговый припев с повторами, простая лексика, нерв и дерзость, без вычурных метафор.'],
  [['поп', 'евродэнс', 'диско', 'синт-поп'], 'Простые цепляющие рифмы, яркий припев-хук, который хочется подпевать, структура куплет-припев-куплет-припев-бридж-припев.'],
  [['блюз'], 'Блюзовая трёхстрочная строфа AAB: первая строка повторяется, третья отвечает, образы дороги, любви и утраты.'],
  [['рэп', 'хип-хоп', 'трэп'], 'Плотная сетка рифм в строке, панчлайны, поток речи важнее напева; припев может быть коротким хуком.'],
  [['фолк', 'бард', 'авторск'], 'Повествовательный сюжет, разговорная интонация, образы простые и конкретные, припев — рефрен-обобщение.'],
  [['мантра', 'киртан'], 'Строки-заклинания с повторами, короткие фразы, распеваемые слоги, медитативное нарастание.'],
  [['регги', 'даб'], 'Лёгкий солнечный тон, простой запоминающийся припев, повторяющийся между куплетами.'],
  [['метал', 'трэш', 'дум'], 'Мрачные образы, эпичность, припев-марш с повторяющимся заглавием.'],
  [['рок'], 'Энергичные куплеты, припев-крик-лозунг, образы дороги и свободы.'],
  [['джаз', 'босса', 'лаунж'], 'Изящные образы, лёгкая ирония, ночной город, строки дышат свободно.'],
  [['эмбиент', 'электрон', 'техно', 'лоу-фай', 'чилаут'], 'Минимум слов: короткие фразы-впечатления, припев может быть почти без слов, атмосфера важнее сюжета.'],
  [['готик', 'дарк'], 'Мрачная романтика, сумрак, глубокие образы, торжественный припев.'],
]

const FEMALE = /женск|женск|девушк|she|female/i
const MALE = /мужск|юнош|he\b|male/i

/**
 * Инструкция копайтеру из слотов формы.
 * @param {{language?: string, genre?: string, vocals?: string}} slots слоты формы
 * @returns {string} текст инструкции (редактируемый)
 */
export function buildCopilotInstruction(slots = {}) {
  const lang = slots.language || 'Russian'
  const parts = []
  parts.push(`Пиши текст песни на языке: ${lang}. Секционная разметка [Verse], [Chorus] (можно [Bridge], [Outro]). В ответе — только текст песни: без пояснений, без markdown, без названия.`)

  const v = slots.vocals || ''
  if (FEMALE.test(v)) parts.push('Песня от лица женщины.')
  else if (MALE.test(v)) parts.push('Песня от лица мужчины.')

  const genreText = `${slots.genre || ''} ${v}`.toLowerCase()
  for (const [keys, rule] of GENRE_RULES) {
    if (keys.some((k) => genreText.includes(k))) {
      parts.push(`Жанровые правила стиха: ${rule}`)
      break
    }
  }

  parts.push('Строки короткие и поёмые. Два-три куплета и припев.')
  return parts.join('\n')
}
