  playFile: (id, file, dur) => YuePlayFile(id, file, dur),
  playAudio: (id) => YuePlayAudio(id),
  translate: (text) => YueTranslate(text),
  stopAudio: () => YueStopAudio(),
  toggleAudio: () => YueToggleAudio(),
