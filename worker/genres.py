def _load_fx() -> dict:
    return {p["id"]: p for p in json.loads(FX_PRESETS_JSON.read_text(encoding="utf-8"))}


# цели громкости бочки и малого к треку: замена ударов идёт по уровню исходных, цель двигает уже новые удары
# (цель на всю дорожку «барабаны» вернула бы в микс старые удары под новыми). В электронике бочка впереди,
# в тихих (мастер soft) — барабаны глубже
DRUM_LEVELS = {"default": (-11.0, -12.0), "Электроника": (-9.0, -12.0)}


def _drums(fx: dict, kit: str, treat: str, levels: tuple) -> list:
    """Части барабанов набором: готовая цепочка части (drums-<часть>-kit — живой osdk, drums-<часть>-<машина>)
    + обработка ритм-секции; у бочки и малого — цель громкости."""
    out = []
    for part in DRUM_PARTS:
        pid = f"drums-{part}-kit" if kit == "osdk" else f"drums-{part}-{kit}"
        spec = {"stems": [part], "engine": copy.deepcopy(fx[pid]["chain"]) + copy.deepcopy(TREATMENTS[treat])}
        if part in ("kick", "snare"):
            spec["level_db"] = levels[0] if part == "kick" else levels[1]
        out.append(spec)
    return out


def _part(fx: dict, pid: str, sections: list) -> dict:
    p = fx[pid]
    chain = [{k: v for k, v in b.items() if k != "notes"} for b in copy.deepcopy(p["chain"])]
    first = chain[0]["type"]
    out = {"kind": first, "engine": chain, "sections": list(sections)}
    if first == "synth":
        out.update(style=p.get("style", "pad"), octave=int(p.get("octave", 0)))
    else:
        out.update(pattern=p.get("pattern", "eighths"), swing=float(p.get("swing", 0)), accent=1.0)
    if p.get("place"):
        out["place"] = dict(p["place"])
    return out


def build() -> list:
    """Встроенные жанровые пресеты: [{slug, name, note, family, specs, final, parts, master, target_lufs, …}]."""
    fx = _load_fx()
    out = []
    for family, genre, gslug, variants in GENRES:
        for vslug, vname, note, kit, treat, bass, bass_lv, gtr, gtr_lv, parts, master in variants:
            chain, target = MASTERS[master]
            kick, snare = DRUM_LEVELS.get(family, DRUM_LEVELS["default"])
            if master == "soft":
                kick, snare = kick - 2, snare - 2
            specs = _drums(fx, kit, treat, (kick, snare))
            specs.append({"stems": ["bass"], "engine": copy.deepcopy(fx[bass]["chain"]), "level_db": float(bass_lv)})
            specs.append({"stems": ["guitar"], "engine": copy.deepcopy(fx[gtr]["chain"]), "level_db": float(gtr_lv)})
            out.append(
                {
                    "slug": f"{gslug}-{vslug}",
                    "name": f"{genre} · {vname}",
                    "note": note,
                    "family": family,
                    "reference_job_id": None,
                    "specs": specs,
                    "final": [],
                    "parts": [_part(fx, pid, secs) for pid, secs in parts],
                    "master": copy.deepcopy(chain),
                    "target_lufs": target,
                }
            )
    return out
